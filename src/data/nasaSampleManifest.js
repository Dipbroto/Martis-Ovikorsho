// Total sample tubes on Perseverance
export const TOTAL_MSR_TUBES = 38;

/**
 * Returns summary statistics of the NASA sample return manifest.
 */
export function getMsrManifestStats(manifest = NASA_MSR_MANIFEST) {
  const threeForksTubes = manifest.filter((t) => t.depotLocation === 'Three Forks Depot');
  const onboardTubes = manifest.filter((t) => t.depotLocation === 'Onboard Rover Belly Cache');
  const totalSealedMassG = manifest.reduce((acc, t) => acc + (t.coreMassG || 0), 0);
  const totalCoredLengthMm = manifest.reduce((acc, t) => acc + (t.coreLengthMm || 0), 0);

  const sedimentaryCount = manifest.filter((t) => t.sampleType.includes('Sedimentary')).length;
  const igneousCount = manifest.filter((t) => t.sampleType.includes('Igneous')).length;
  const regolithCount = manifest.filter((t) => t.sampleType.includes('Regolith')).length;
  const atmosphericCount = manifest.filter((t) => t.sampleType.includes('Atmospheric')).length;
  const witnessCount = manifest.filter((t) => t.sampleType.includes('Witness')).length;
  const openTubes = TOTAL_MSR_TUBES - manifest.length;

  return {
    totalTubes: TOTAL_MSR_TUBES,
    sealedCount: manifest.length,
    openTubes: Math.max(0, openTubes),
    threeForksCount: threeForksTubes.length,
    onboardCount: onboardTubes.length,
    totalSealedMassG: Math.round(totalSealedMassG * 10) / 10,
    totalCoredLengthMm: Math.round(totalCoredLengthMm * 10) / 10,
    sedimentaryCount,
    igneousCount,
    regolithCount,
    atmosphericCount,
    witnessCount,
  };
}
